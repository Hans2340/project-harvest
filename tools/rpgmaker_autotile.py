#!/usr/bin/env python3
"""Convert RPG Maker MV/MZ floor autotiles (A1/A2 layout) into a 47-tile
"blob" atlas for Godot, plus a 256-entry neighbour-mask lookup table.

RPG Maker autotile block (one frame) = 2 x 3 tiles, built from quarter tiles:
  - top-left tile:   preview (unused)
  - top-right tile:  inner corners
  - bottom 2x2:      a patch whose outer ring = edges/outer corners, centre = fill

Usage (from repo root):
  python3 tools/rpgmaker_autotile.py

Edit JOBS below to add more autotiles. Requires Pillow.
"""
from itertools import product
from pathlib import Path
from PIL import Image

T = 48            # RPG Maker tile size
Q = T // 2        # quarter tile
PER_ROW = 8       # tiles per atlas row

# Neighbour bits (same-terrain neighbours)
N, NE, E, SE, S, SW, W, NW = 1, 2, 4, 8, 16, 32, 64, 128

# Quarter source coords (in quarter units) for each quarter and state.
# States: corner, vert_edge (only the vertical neighbour is same),
#         horiz_edge (only the horizontal neighbour is same), inner, fill
QUARTERS = {
    "TL": {"corner": (0, 2), "vert": (0, 4), "horiz": (2, 2), "inner": (2, 0), "fill": (2, 4)},
    "TR": {"corner": (3, 2), "vert": (3, 4), "horiz": (1, 2), "inner": (3, 0), "fill": (1, 4)},
    "BL": {"corner": (0, 5), "vert": (0, 3), "horiz": (2, 5), "inner": (2, 1), "fill": (2, 3)},
    "BR": {"corner": (3, 5), "vert": (3, 3), "horiz": (1, 5), "inner": (3, 1), "fill": (1, 3)},
}
# (vertical neighbour, horizontal neighbour, diagonal) per quarter
QUARTER_NEIGHBOURS = {"TL": (N, W, NW), "TR": (N, E, NE), "BL": (S, W, SW), "BR": (S, E, SE)}
ORDER = ("TL", "TR", "BL", "BR")
OFFSETS = {"TL": (0, 0), "TR": (Q, 0), "BL": (0, Q), "BR": (Q, Q)}


def quarter_state(mask, q):
    v, h, d = QUARTER_NEIGHBOURS[q]
    v, h, d = bool(mask & v), bool(mask & h), bool(mask & d)
    if not v and not h:
        return "corner"
    if v and not h:
        return "vert"
    if h and not v:
        return "horiz"
    return "fill" if d else "inner"


def build_table():
    """Returns (shapes, table): shapes = unique quarter-state tuples (47),
    table[mask] = index into shapes."""
    shapes, table = [], []
    for mask in range(256):
        key = tuple(quarter_state(mask, q) for q in ORDER)
        if key not in shapes:
            shapes.append(key)
        table.append(shapes.index(key))
    return shapes, table


def render_tile(block, shape):
    tile = Image.new("RGBA", (T, T))
    for q, state in zip(ORDER, shape):
        qx, qy = QUARTERS[q][state]
        piece = block.crop((qx * Q, qy * Q, qx * Q + Q, qy * Q + Q))
        tile.paste(piece, OFFSETS[q])
    return tile


def convert(src, out, frames=1, frame_order=None, extra_first_tile=None):
    """src: image with `frames` autotile blocks side by side (96 px each).
    Atlas layout: tile i at column (i % PER_ROW) * len(frame_order), row i // PER_ROW,
    with its animation frames in consecutive columns (Godot tile animation)."""
    img = Image.open(src).convert("RGBA")
    blocks = [img.crop((f * 2 * T, 0, f * 2 * T + 2 * T, 3 * T)) for f in range(frames)]
    frame_order = frame_order or list(range(frames))
    shapes, _ = build_table()
    count = len(shapes) + (1 if extra_first_tile else 0)
    fpt = len(frame_order)
    rows = (count + PER_ROW - 1) // PER_ROW
    atlas = Image.new("RGBA", (PER_ROW * fpt * T, rows * T))
    idx = 0
    if extra_first_tile:
        for k in range(fpt):
            atlas.paste(extra_first_tile, (k * T, 0))
        idx = 1
    for shape in shapes:
        cx, cy = (idx % PER_ROW) * fpt, idx // PER_ROW
        for k, f in enumerate(frame_order):
            atlas.paste(render_tile(blocks[f], shape), ((cx + k) * T, cy * T))
        idx += 1
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    atlas.save(out)
    print(f"wrote {out}: {count} tiles x {fpt} frame(s)")


def write_gd_table(path):
    shapes, table = build_table()
    rows = ",\n".join("\t" + ", ".join(str(v) for v in table[i:i + 16]) for i in range(0, 256, 16))
    Path(path).write_text(f'''class_name BlobAutotile
extends RefCounted
## GENERATED by tools/rpgmaker_autotile.py - do not edit by hand.
## Maps an 8-neighbour mask to one of {len(shapes)} blob tiles.
## Bits: N=1, NE=2, E=4, SE=8, S=16, SW=32, W=64, NW=128 (neighbour is same terrain).

const TILE_COUNT := {len(shapes)}
const PER_ROW := {PER_ROW}

const TABLE: Array[int] = [
{rows},
]


## Neighbour mask for `cell`, where `is_same` is a Callable(Vector2i) -> bool.
static func mask_at(cell: Vector2i, is_same: Callable) -> int:
	var m := 0
	var dirs := [Vector2i(0, -1), Vector2i(1, -1), Vector2i(1, 0), Vector2i(1, 1),
		Vector2i(0, 1), Vector2i(-1, 1), Vector2i(-1, 0), Vector2i(-1, -1)]
	for i in 8:
		if is_same.call(cell + dirs[i]):
			m |= 1 << i
	return m
''')
    print(f"wrote {path}")


if __name__ == "__main__":
    raw = Path("assets/tilesets/dark_swamp/raw")
    gen = Path("assets/tilesets/dark_swamp/generated")
    plain = Image.new("RGBA", (T, T), (52, 83, 24, 255))  # pack's grass colour #345318
    # Ground: tile 0 = plain grass fill, tiles 1..47 = leafy-grass blob
    convert(raw / "GroundTileset.png", gen / "swamp_ground_blob.png", frames=1, extra_first_tile=plain)
    # Water: 3 frames; loop 0,1,2,1 (pack README tip for smoother animation)
    convert(raw / "WaterAnimation.png", gen / "swamp_water_blob.png", frames=3, frame_order=[0, 1, 2, 1])
    write_gd_table("scripts/world/blob_autotile.gd")
